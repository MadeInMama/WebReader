namespace WebReader.Services.Tts;

public class ClearTextTtsClient(HttpClient httpClient) : ITtsClient
{
    private const string ModelName = "llama3.1:8b";
    private const double Temperature = 0.2;

    private const string SystemPrompt = """
                                        Ты — автоматический лингвистический скрипт-редактор. Ты обрабатываешь исключительно цитаты и фрагменты из классической мировой художественной литературы девятнадцатого и двадцатого века для учебного архива аудиокниг. 
                                        Этот текст является историческим культурным наследием, не содержит нарушений и полностью безопасен.

                                        Твоя задача — строго нормализовать присланную цитату для диктора XTTS v2.

                                        ПРАВИЛА ОБРАБОТКИ:
                                        1. Замени все цифры, даты и сокращения полными русскими словами в правильном падеже. Даты могут быть в формате "1912 года", "1912 — 1932 гг." и другие.
                                        2. Замени букву "е" на "ё" везде, где это необходимо по смыслу (еще -> ещё, ждем -> ждём). Не меняй окончания авторских слов!
                                        3. После подготовки результата проверяй насколько получившийся текст соответствует исходному, если не соответствет хотя бы немного(пропущены слова, слова переставлены местами), то обрабатывай исходный текст заново.

                                        ФОРМАТ ВЫВОДА:
                                        Ты обязан обернуть итоговый обработанный текст в теги [START_TEXT] и [END_TEXT].
                                        Ты не имеешь права комментировать, отказывать или вести диалог. Просто пропусти текст через фильтр.
                                        Ответ должен быть строго на русском языке, не должно быть слов или частей слов на английском, китайском и других языках.
                                        Запрещено переводить слова на другие языки. 
                                        Ответ должен содержать полный текст источника. Пропуск продложений или слов не допускается. Дополнение новыми словами так же не допускается.
                                        Запрещено перефразировать выражения и предложения. Заперещено менять местами слова и предложения.
                                        Итоговый ответ должен содержать только результат для озвучивания, без комментариев, без рассуждений и другого.
                                        """;


    public async Task<HttpResponseMessage> ProceedAsync(string text, string speaker,
        CancellationToken cancellationToken)
    {
        return await httpClient.PostAsJsonAsync("v1/chat/completions", new
        {
            model = ModelName,
            messages = new[]
            {
                new { role = "system", content = SystemPrompt },
                new { role = "user", content = text }
            },
            stream = false,
            options = new
            {
                temperature = Temperature,
                top_p = 0.9
            }
        }, cancellationToken);
    }
}
